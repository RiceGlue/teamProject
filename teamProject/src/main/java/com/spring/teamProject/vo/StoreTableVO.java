package com.spring.teamProject.vo;

public class StoreTableVO {
	private String table_id;
	private String store_id;
	private String table_info;
	private String capacity;
	private String pos_x;
	private String pos_y;
	
	
	public String getTable_id() {
		return table_id;
	}
	public void setTable_id(String table_id) {
		this.table_id = table_id;
	}
	public String getStore_id() {
		return store_id;
	}
	public void setStore_id(String store_id) {
		this.store_id = store_id;
	}
	public String getTable_info() {
		return table_info;
	}
	public void setTable_info(String table_info) {
		this.table_info = table_info;
	}
	public String getCapacity() {
		return capacity;
	}
	public void setCapacity(String capacity) {
		this.capacity = capacity;
	}
	public String getPos_x() {
		return pos_x;
	}
	public void setPos_x(String pos_x) {
		this.pos_x = pos_x;
	}
	public String getPos_y() {
		return pos_y;
	}
	public void setPos_y(String pos_y) {
		this.pos_y = pos_y;
	}
	
	
}
